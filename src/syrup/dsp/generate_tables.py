#!/usr/bin/env python3
"""Rebuild original Syrup control tables with the Python standard library."""
import argparse
import math
from pathlib import Path


HEADER = "// Generated by generate_tables.py. Values come from the equations in that file.\n"


def array(name, word, values):
    rows = [", ".join(str(value) for value in values[i:i + 8]) for i in range(0, len(values), 8)]
    return f"constexpr {word} {name}[] = {{\n" + "".join(f"    {row},\n" for row in rows) + "};\n"


def render():
    intervals = [(45, 180, 16), (180, 5000, 64), (5000, 17000, 32)]
    cutoff = [minimum * (maximum / minimum) ** (i / count)
              for minimum, maximum, count in intervals for i in range(count)] + [17000]
    drive_db = [18 * i / 64 for i in range(65)]
    trim_db = [-6 + 12 * i / 64 for i in range(65)]
    tables = [array("cutoff_hz_milli", "u32", [round(hz * 1000) for hz in cutoff])]
    for rate in (44100, 48000):
        tables.append(array(f"cutoff_tangent_{rate}", "u16",
                            [round(math.tan(math.pi * hz / rate) * (1 << 14)) for hz in cutoff]))
    tables.append(array("input_gain", "u16", [round(10 ** (db / 20) * (1 << 12)) for db in drive_db]))
    tables.append(array("drive_compensation", "u16",
                        [round(10 ** (-0.35 * db / 20) * (1 << 15)) for db in drive_db]))
    tables.append(array("trim_gain", "u16", [round(10 ** (db / 20) * (1 << 14)) for db in trim_db]))
    return HEADER + "\n" + "\n".join(tables)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = Path(__file__).with_name("tables.inc")
    content = render()
    if args.check:
        if output.read_text() != content:
            raise SystemExit("Syrup control tables differ from their generating equations")
    else:
        output.write_text(content)


if __name__ == "__main__":
    main()
